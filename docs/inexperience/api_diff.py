import json
import sys
from pathlib import Path


def load_counts(path):
    out = {}
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        count, _, name = line.partition("\t")
        if count.isdigit():
            out[name] = out.get(name, 0) + int(count)
    return out


def main():
    old_path, new_path, inventory, out_path = sys.argv[1:5]
    old = json.loads(Path(old_path).read_text(encoding="utf-8"))
    new = json.loads(Path(new_path).read_text(encoding="utf-8"))
    inv = Path(inventory)
    strings = load_counts(inv / "strings.txt")
    keys = load_counts(inv / "keys.txt")
    methods = load_counts(inv / "methods.txt")
    globals_ = load_counts(inv / "globals.txt")

    old_classes = {c["name"]: c for c in old["classes"]}
    old_members = {}
    for c in old["classes"]:
        names = set()
        for kind in ("properties", "functions", "events", "callbacks", "yield_functions"):
            names.update(m["name"] for m in c[kind])
        old_members[c["name"]] = names
    old_enums = {e["name"]: {i["name"] for i in e["items"]} for e in old["enums"]}

    new_classes = {c["Name"]: c for c in new["Classes"]}

    def inherited_old(name):
        seen = set()
        while name and name in old_classes:
            seen |= old_members[name]
            name = old_classes[name]["superclass"]
        return seen

    def used_member(name, kind):
        if kind == "Function":
            return methods.get(name, 0) + keys.get(name, 0)
        return keys.get(name, 0) + strings.get(name, 0)

    lines = ["# InExperience backport list", ""]
    lines.append(
        "Generated by `docs/inexperience/api_diff.py` from the 2016 reflection database, "
        "the version-67c8b1dedbb74fed Full API dump and the bytecode inventory of "
        "InExperience.rbxm (version-f0ea5da9412f4e35). A class counts as used when its name "
        "appears in a module string table; a member counts as used when its name is read, "
        "written or called through GETTABLEKS, SETTABLEKS or NAMECALL, or appears as a string."
    )
    lines.append("")

    used_new = sorted(n for n in new_classes if n not in old_classes and strings.get(n))
    unused_new = sorted(n for n in new_classes if n not in old_classes and not strings.get(n))
    lines.append(f"## New classes referenced ({len(used_new)})")
    lines.append("")
    for n in used_new:
        c = new_classes[n]
        tags = ",".join(t for t in (c.get("Tags") or []) if isinstance(t, str))
        lines.append(f"- `{n}` : {c['Superclass']} (string uses {strings[n]}){' [' + tags + ']' if tags else ''}")
    lines.append("")

    lines.append("## New members on referenced classes")
    lines.append("")
    total = 0
    for n in sorted(new_classes):
        if not strings.get(n) and n not in old_classes:
            continue
        if n in old_classes and not strings.get(n):
            continue
        have = inherited_old(n) if n in old_classes else set()
        rows = []
        for m in new_classes[n]["Members"]:
            if m["Name"] in have:
                continue
            tags = [t for t in (m.get("Tags") or []) if isinstance(t, str)]
            if "Deprecated" in tags or "Hidden" in tags or "NotScriptable" in tags:
                continue
            sec = m.get("Security")
            sec = sec if isinstance(sec, str) else (sec or {}).get("Read", "None")
            if sec not in ("None", "PluginSecurity", "RobloxScriptSecurity"):
                continue
            u = used_member(m["Name"], m["MemberType"])
            if not u:
                continue
            vt = m.get("ValueType", {}).get("Name", "") if m["MemberType"] == "Property" else ""
            rows.append(f"  - {m['MemberType']} `{m['Name']}`{' : ' + vt if vt else ''} ({u}) {sec}")
        if rows:
            total += len(rows)
            lines.append(f"- `{n}`")
            lines.extend(rows)
    lines.append("")
    lines.append(f"{total} members.")
    lines.append("")

    enum_uses = {}
    for g, count in globals_.items():
        parts = g.split(".")
        if parts[0] == "Enum" and len(parts) >= 2:
            enum_uses.setdefault(parts[1], set())
            if len(parts) == 3:
                enum_uses[parts[1]].add(parts[2])
    lines.append("## Enums referenced through Enum.X.Y imports")
    lines.append("")
    new_enums = {e["Name"]: {i["Name"] for i in e["Items"]} for e in new["Enums"]}
    for e in sorted(enum_uses):
        items = sorted(enum_uses[e])
        if e not in old_enums:
            lines.append(f"- `{e}` new: {', '.join(items)}")
        else:
            missing = [i for i in items if i not in old_enums[e]]
            if missing:
                lines.append(f"- `{e}` new items: {', '.join(missing)}")
        unknown = [i for i in items if e in new_enums and i not in new_enums[e]]
        if unknown:
            lines.append(f"  - not in the 2026 dump either: {', '.join(unknown)}")
    lines.append("")
    lines.append(f"## New classes not referenced ({len(unused_new)})")
    lines.append("")
    lines.append(", ".join(f"`{n}`" for n in unused_new))
    lines.append("")
    Path(out_path).write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
